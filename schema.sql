-- SMARTPARK DATABASE SCHEMA
-- Run in Supabase SQL Editor only for a new/empty project.
-- If you already created these tables/functions/policies in your project, do not rerun blindly.

create extension if not exists btree_gist;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  phone text not null default '',
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.parking_slots (
  id bigint generated by default as identity primary key,
  location_name text not null,
  slot_number text not null,
  current_status text not null default 'Available' check (current_status in ('Available','Occupied')),
  created_at timestamptz not null default now(),
  unique(location_name,slot_number)
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  booking_reference text not null unique default ('SP' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,10))),
  user_id uuid not null references public.profiles(id),
  slot_id bigint not null references public.parking_slots(id),
  booking_date date not null,
  entry_time time not null,
  exit_time time not null,
  booking_status text not null default 'Confirmed' check (booking_status in ('Confirmed','Cancelled','Completed')),
  reservation_period tsrange generated always as (
    tsrange(booking_date + entry_time, booking_date + exit_time, '[)')
  ) stored,
  created_at timestamptz not null default now(),
  constraint booking_exit_after_entry check (exit_time > entry_time)
);

do $$ begin
  alter table public.bookings add constraint no_overlapping_confirmed_bookings
  exclude using gist (
    slot_id with =,
    reservation_period with &&
  ) where (booking_status = 'Confirmed');
exception when duplicate_object then null;
end $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id,full_name,email,phone)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name',''),
    coalesce(new.email,''),
    coalesce(new.raw_user_meta_data->>'phone','')
  )
  on conflict (id) do update set
    full_name=excluded.full_name,
    email=excluded.email,
    phone=excluded.phone;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=''
as $$
  select exists (
    select 1 from public.profiles
    where id=(select auth.uid()) and role='admin'
  );
$$;

create or replace function public.create_booking(
  p_slot_id bigint,
  p_booking_date date,
  p_entry_time time,
  p_exit_time time
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_reference text;
begin
  if v_user is null then raise exception 'Please log in before booking.'; end if;
  if p_booking_date < current_date then raise exception 'Booking date cannot be in the past.'; end if;
  if p_exit_time <= p_entry_time then raise exception 'Exit time must be later than entry time.'; end if;
  if not exists(select 1 from public.parking_slots where id=p_slot_id) then
    raise exception 'Selected parking slot does not exist.';
  end if;

  insert into public.bookings(user_id,slot_id,booking_date,entry_time,exit_time)
  values(v_user,p_slot_id,p_booking_date,p_entry_time,p_exit_time)
  returning booking_reference into v_reference;

  return v_reference;
exception
  when exclusion_violation then
    raise exception 'This slot is already reserved for the selected time. Please choose another slot or time.';
end;
$$;

create or replace function public.cancel_booking(p_booking_reference text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.bookings
  set booking_status='Cancelled'
  where booking_reference=p_booking_reference
    and user_id=auth.uid()
    and booking_status='Confirmed';
  if not found then raise exception 'Booking not found or cannot be cancelled.'; end if;
end;
$$;

alter table public.profiles enable row level security;
alter table public.parking_slots enable row level security;
alter table public.bookings enable row level security;

drop policy if exists "Users can view own profile" on public.profiles;
create policy "Users can view own profile" on public.profiles
for select to authenticated using (id=(select auth.uid()) or public.is_admin());

drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles
for update to authenticated using (id=(select auth.uid())) with check (id=(select auth.uid()));

drop policy if exists "Authenticated users can view parking slots" on public.parking_slots;
create policy "Authenticated users can view parking slots" on public.parking_slots
for select to authenticated using (true);

drop policy if exists "Admins can insert parking slots" on public.parking_slots;
create policy "Admins can insert parking slots" on public.parking_slots
for insert to authenticated with check (public.is_admin());

drop policy if exists "Admins can update parking slots" on public.parking_slots;
create policy "Admins can update parking slots" on public.parking_slots
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Users can view own bookings" on public.bookings;
create policy "Users can view own bookings" on public.bookings
for select to authenticated using (user_id=(select auth.uid()) or public.is_admin());

revoke insert, update, delete on public.bookings from anon, authenticated;
grant execute on function public.create_booking(bigint,date,time,time) to authenticated;
grant execute on function public.cancel_booking(text) to authenticated;
grant execute on function public.is_admin() to authenticated;

